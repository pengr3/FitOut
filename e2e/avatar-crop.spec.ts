// CROP-01 — THE CROP STAGE, MEASURED IN A REAL BROWSER, BECAUSE THERE IS NOWHERE ELSE IT EXISTS.
//
// ═════════════════════════════════════════════════════════════════════════════════════════════════
// WHY THIS FILE EXISTS AT ALL, AND WHY A VITEST SPEC COULD NOT HAVE STOOD IN FOR IT
// ═════════════════════════════════════════════════════════════════════════════════════════════════
//
// `react-easy-crop@6.2.3` renders the crop-area element — the one carrying `tabIndex`, the
// `aria-label`, the round mask and the scrim — ONLY when `this.state.cropSize` is truthy, and
// `cropSize` is set only by `computeSizes()`, which needs a non-zero `containerRef
// .getBoundingClientRect()` AND a decoded `<img>` reporting real naturals.
//
// Probed jsdom 29.1.1 (16-RESEARCH § E) has NEITHER: `getContext("2d")` → `null`;
// `createImageBitmap`, `OffscreenCanvas`, `ResizeObserver`, `URL.createObjectURL` and
// `Image.prototype.decode` → all `undefined`; and every `getBoundingClientRect()` → zeros.
//
//   ⚠ IN JSDOM THE CROP STAGE DOES NOT EXIST IN THE DOM. Not "renders differently" — is absent.
//
// So everything geometric, gestural or pixel-bearing is Playwright or a human, and this file is the
// Playwright half's foundation. The repo has stubbed `ResizeObserver` five times and has NEVER
// stubbed `getBoundingClientRect`; two specs record in prose that they refuse to pretend jsdom has
// layout. This file is the other side of that refusal — the measurements those specs declined to
// fake, taken where they are real.
//
// ═════════════════════════════════════════════════════════════════════════════════════════════════
// TWO CONVENTIONS THIS FILE INTRODUCES, BECAUSE NOTHING IN `e2e/` HAD EITHER
// ═════════════════════════════════════════════════════════════════════════════════════════════════
//
// (1) DRIVING A FILE INPUT. `grep -rn "setInputFiles" e2e/` returned NOTHING before this file. The
//     avatar picker is the only `<input type="file">` in `src/`, it is `className="hidden"`, and it
//     is deliberately unregistered with react-hook-form. `locator.setInputFiles()` sets a hidden
//     input's `files` and dispatches `change`, which is the whole of what the shipped
//     `onAvatarChange` needs — so the bytes fed to the four guards and to the browser's own decoder
//     are the committed `e2e/fixtures/` bytes, generated by `scripts/generate-image-fixtures.mjs`
//     and gated byte-for-byte by `tests/design/image-fixtures.test.ts`. A real decoder on real
//     committed bytes is what makes the `corrupt.jpg` case honest; plan 16-10's jsdom version had to
//     mock `measureImage`, so what it proved was that the branch existed, not that it fires.
//
// (2) READING COMPUTED STYLE. `page.evaluate((el) => getComputedStyle(el)...)` answers cascade
//     questions no source scan can. The library injects its own stylesheet UNLAYERED into the
//     document head while Tailwind v4 utilities live in a cascade layer, and unlayered beats
//     layered — so "the class is in the source" and "the rule wins" are different claims here, and
//     only the second one is a behaviour. Every computed-style assertion below is a VERIFICATION of
//     a rule the library already ships, never a re-authoring of one.
//
// ═════════════════════════════════════════════════════════════════════════════════════════════════
// ⚠ THIS FILE DOES NOT DISCHARGE CROP-04. IT PRODUCES EVIDENCE FOR CROP-01.
