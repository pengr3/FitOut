async function pick(page: Page, name: string): Promise<void> {
  await page.locator('input[type="file"]').setInputFiles(fixture(name));
}

/**
 * Wait for every running CSS animation in the document to finish before measuring anything.
 *
 * ⚠ NOT A SLEEP, AND NOT OPTIONAL — IT WAS MEASURED. `ui/dialog.tsx:73` puts
 * `data-open:animate-in data-open:zoom-in-95 duration-100` on `DialogContent`, which is a SCALE, and
 * `boundingBox()` reports the TRANSFORMED rect. Probed 2026-08-25 without this call: the 1280x800
 * stage measured **319.7356872558594px** rather than 320 — a box caught at ~99.9% of the way through
 * a 100ms zoom. It passed the 1px band by 0.26px, which is the worst possible outcome: a geometry
 * assertion whose margin is a race rather than a tolerance.
 *
 * `document.getAnimations()` returns the live CSS animations (tailwindcss-animate compiles
 * `animate-in` to a keyframe animation, not a transition), so awaiting their `finished` promises
 * waits for exactly the thing in the way and nothing else. `.catch()` swallows the rejection an
 * animation raises if it is cancelled mid-flight — a cancelled animation is a settled one for this
 * purpose.
 */
async function settleAnimations(page: Page): Promise<void> {
  await page.evaluate(() =>
    Promise.all(document.getAnimations().map((a) => a.finished.catch(() => undefined))),
  );
}

